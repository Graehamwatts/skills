class ValidatorCatches(unittest.TestCase):
    def setUp(self):
        self.d = load("ledger_small.json")
        self.b = load("ledger_busy.json")

    def expect(self, d, fragment, **kw):
        problems = C.validate_ledger(d, **kw)
        self.assertTrue(any(fragment in p for p in problems), "expected %r in %r" % (fragment, problems[:6]))

    def test_feedback_only_keys_are_rejected(self):
        for key in ("recommendation", "decision_log", "seller_ask"):
            d = copy.deepcopy(self.d)
            d[key] = None
            self.expect(d, "key %r is not allowed" % key)
            d = copy.deepcopy(self.d)
            d["pricing_tally"][key] = "Reduce to $1,150,000."
            self.expect(d, "key %r is not allowed" % key)

    def test_provenance_stays_out_of_the_ledger(self):
        self.d["contacts"][0]["provenance"] = {"tab": "showing", "row": 4}
        self.expect(self.d, "key 'provenance' is not allowed")

    def test_numbers_must_match_the_rows(self):
        cases = [(("totals", "touches_outbound"), "totals.touches_outbound"), (("totals", "replied"), "totals.replied"),
                 (("pricing_tally", "not_raised"), "pricing_tally.not_raised"), (("report", "days_on_market"), "report.days_on_market")]
        for (block, key), fragment in cases:
            d = copy.deepcopy(self.d)
            d[block][key] += 1
            self.expect(d, fragment)
        d = copy.deepcopy(self.d)
        d["weeks"][2]["replies_inbound"] += 1
        self.expect(d, "weeks[3].replies_inbound")
        d = copy.deepcopy(self.d)
        d["totals"]["showings"] += d["totals"]["inquiries"]              # an inquiry counted as a showing
        self.expect(d, "totals.showings")
        d = copy.deepcopy(self.d)
        d["totals"]["tours_and_inquiries"] = 3
        self.expect(d, "totals.tours_and_inquiries: unknown key")
        d = copy.deepcopy(self.d)
        d["themes_tally"]["rows"][0]["people"] += 1
        self.expect(d, "themes_tally.rows")
        d = copy.deepcopy(self.b)
        d["price_periods"][1]["offers"] = 1
        self.expect(d, "price_periods")
        d = copy.deepcopy(self.b)
        d["offers"][0]["pct_of_list"] = 101.0
        self.expect(d, "pct_of_list")

    def test_quiet_weeks_cannot_be_dropped(self):
        del self.d["weeks"][1]
        self.expect(self.d, "quiet weeks are kept")

    def test_the_week_must_be_monday_to_sunday(self):
        self.d["report"]["week_start"] = "2026-04-07"
        self.expect(self.d, "is not a Monday")

    def test_tags_must_agree_with_the_rows(self):
        d = copy.deepcopy(self.d)
        contact(d, "c003")["status"] = "replied"
        self.expect(d, "has not been answered")
        d = copy.deepcopy(self.d)
        contact(d, "c001")["status"] = "awaiting_reply"
        self.expect(d, "awaiting_reply, but")
        d = copy.deepcopy(self.d)
        contact(d, "c002")["price_reaction"] = "too_high"
        self.expect(d, "contacts[c002].price_reaction")
        d = copy.deepcopy(self.d)
        contact(d, "c002")["themes"].append("price")
        self.expect(d, "'price' is not in themes_vocabulary")
        d = copy.deepcopy(self.d)
        contact(d, "c002")["interest"] = "warm"
        self.expect(d, "status 'passed' and interest 'passed' go together")
        d = copy.deepcopy(self.d)
        contact(d, "c006")["touches"] = [dict(contact(d, "c003")["touches"][0])]
        self.expect(d, "carries no touches of their own")

