class Names(unittest.TestCase):
    def test_short_name(self):
        cases = {
            "Yang Li": "Yang L.", "yang li": "Yang L.", "YANG LI": "Yang L.", "Yang  Li\n(Harbor)": "Yang L.",
            "Robert (Bob) Hale": "Robert H.", "Yang Li (buyer lead from open house)": "Yang L.",
            "Kestrel": "Kestrel", "Hale, Robert": "Robert H.", "Yang Li, Realtor": "Yang L.",
            "Ann Lee / Teo Park": "Ann L.", "Ann & Bob Lee": "Ann L.", "Dr. Ann Lee Jr.": "Ann L.",
            "Marisol Garcia-Lopez": "Marisol G.", "Ana Lucia Vega": "Ana V.", "Declan O'Brien": "Declan O.",
            "DeShawn McDonald": "DeShawn M.", "Yang L.": "Yang L.", "Yang Li 650.555.0100": "Yang L.",
            "Invited by Yang Li": "Client of Yang L.", "invited by: Kestrel": "Client of Kestrel",
            "650-555-0100": "", "someone@example.com": "", "": "", None: "",
        }
        for raw, want in cases.items():
            self.assertEqual(C.short_name(raw), want, raw)

    def test_short_name_matches_the_ledger_pattern(self):
        for raw in ("Yang Li", "Kestrel", "Marisol Garcia-Lopez", "Declan O'Brien"):
            self.assertTrue(C.SHORT_NAME.match(C.short_name(raw)), raw)
        self.assertFalse(C.SHORT_NAME.match("Yang Li 650"))

    def test_invited_by(self):
        self.assertEqual(C.invited_by("Invited by Yang Li"), "Yang Li")
        self.assertIsNone(C.invited_by("Yang Li"))

    def test_slugify(self):
        self.assertEqual(C.slugify("218 W Sample Glen Rd #214"), "218-w-sample-glen-rd-214")
        self.assertEqual(C.slugify("  Caf\u00e9 Lane -- Unit 3 "), "cafe-lane-unit-3")

    def test_keys_ignore_position_and_follow_wording(self):
        a = C.row_key("showing", "Yang Li", ["(650) 555-0100"], ["Y@Example.com"])
        self.assertEqual(a, C.row_key("showing", " yang  li ", ["650.555.0100"], ["y@example.com"]))
        self.assertNotEqual(a, C.row_key("disclosure", "Yang Li", ["(650) 555-0100"], ["Y@Example.com"]))
        e = C.entry_key(a, "note", "2026-09-25", "no answer, left a vm")
        self.assertEqual(e, C.entry_key(a, "note", D(2026, 9, 25), "No answer,  left a VM."))
        self.assertNotEqual(e, C.entry_key(a, "note", "2026-09-25", "no answer, left a vm and sent a text"))
        self.assertEqual(e.count("/"), 3)
        with self.assertRaises(ValueError):
            C.row_key("glide", "Yang Li")


class Dates(unittest.TestCase):
    def test_week_is_monday_to_sunday(self):
        self.assertEqual(C.week_start("2026-10-07"), D(2026, 10, 5))
        self.assertEqual(C.week_end("2026-10-05"), D(2026, 10, 11))
        self.assertEqual(C.week_start("2026-10-11"), D(2026, 10, 5))
        self.assertEqual(C.parse_date("2026-10-05T14:13:00-07:00"), D(2026, 10, 5))
        with self.assertRaises(ValueError):
            C.parse_date("10/5/2026")

    def test_week_index_counts_from_the_list_week(self):
        self.assertEqual(C.week_index("2026-07-21", "2026-07-21"), 1)
        self.assertEqual(C.week_index("2026-07-26", "2026-07-21"), 1)
        self.assertEqual(C.week_index("2026-07-27", "2026-07-21"), 2)
        self.assertEqual(C.week_index("2026-10-04", "2026-07-21"), 11)
        self.assertEqual(C.week_index("2026-07-19", "2026-07-21"), 0)

    def test_report_week_is_the_week_just_ended(self):
        want = (D(2026, 10, 5), D(2026, 10, 11), D(2026, 10, 12))
        self.assertEqual(C.report_week("2026-10-12"), want)      # built on the Monday
        self.assertEqual(C.report_week("2026-10-15"), want)      # built late: still the same issue
        self.assertEqual(C.report_week("2026-10-11")[1], D(2026, 10, 4))   # Sunday: that week is not over

    def test_quiet_weeks_are_kept(self):
        weeks = C.list_weeks("2026-07-21", "2026-09-28")
        self.assertEqual(len(weeks), 11)
        self.assertEqual(weeks[0], (1, D(2026, 7, 20), D(2026, 7, 26)))
        self.assertEqual(weeks[-1][1:], (D(2026, 9, 28), D(2026, 10, 4)))

    def test_days_on_market(self):
        self.assertEqual(C.days_on_market("2026-07-21", "2026-10-05"), 76)
        self.assertEqual(C.days_on_market("2026-07-21", "2026-07-21"), 0)

    def test_week_list_price_is_the_price_on_most_days(self):
        hist = [{"date": "2026-07-21", "price": 700}, {"date": "2026-08-01", "price": 800}]
        self.assertEqual(C.week_list_price(hist, "2026-07-21", "2026-07-27", "2026-08-02"), 700)   # 5 days against 2
        hist = [{"date": "2026-09-11", "price": 559}, {"date": "2026-09-12", "price": 569}]
        self.assertEqual(C.week_list_price(hist, "2026-09-11", "2026-09-07", "2026-09-13"), 569)   # listed Friday
        hist = [{"date": "2026-03-02", "price": 1}, {"date": "2026-03-05", "price": 2}, {"date": "2026-03-08", "price": 3}]
        self.assertEqual(C.week_list_price(hist, "2026-03-02", "2026-03-02", "2026-03-08"), 2)     # 3, 3, 1: later of the tie
        self.assertEqual(C.price_on(hist, "2026-03-01"), 1)

    def test_issue_numbers_continue(self):
        self.assertEqual(C.next_issue_number(4, [], "2026-10-12"), 4)
        self.assertEqual(C.next_issue_number(4, [(4, "2026-09-28"), (5, "2026-10-05")], "2026-10-12"), 6)
        self.assertEqual(C.next_issue_number(4, [(4, "2026-09-28"), (5, "2026-10-05")], "2026-10-05"), 5)


class Formatters(unittest.TestCase):
    def test_money_and_dates(self):
        self.assertEqual(C.fmt_money(798888), "$798,888")
        self.assertEqual(C.fmt_money(None), "not recorded")
        self.assertEqual(C.fmt_money_short(798888), "$799K")
        self.assertEqual(C.fmt_money_short(1250000), "$1.25M")
        self.assertEqual(C.fmt_pct(0.983, 1), "98.3%")
        self.assertEqual(C.fmt_date("2026-09-05"), "Sept 5")
        self.assertEqual(C.fmt_date("2026-10-05", year=True, weekday=True), "Mon, Oct 5, 2026")
        self.assertEqual(C.fmt_date("2026-10-05", approximate=True), "about Oct 5")
        self.assertEqual(C.fmt_date_long("2026-10-05"), "Monday, Oct 5, 2026")
        self.assertEqual(C.fmt_range("2026-09-28", "2026-10-04"), "Sept 28 to Oct 4")
        self.assertEqual(C.fmt_count(1, "reply", "replies"), "1 reply")
        self.assertEqual(C.fmt_count(2, "reply", "replies"), "2 replies")
        self.assertEqual(C.join_and(["a", "b", "c"]), "a, b and c")

    def test_no_formatter_emits_a_dash(self):
        outs = [C.fmt_money(-5000), C.fmt_money_short(999), C.fmt_range("2026-01-01", "2026-12-31", year=True),
                C.fmt_date_long("2026-02-28"), C.fmt_pct(None), C.strip_dashes("9/19\u20139/20 \u2014 no one came")]
        for s in outs:
            self.assertFalse(C.has_dash(s), s)
        self.assertEqual(outs[-1], "9/19 to 9/20, no one came")
        self.assertTrue(C.has_dash("a \u2014 b"))
        self.assertTrue(C.has_dash("1\u20132"))

    def test_followup_is_days_first(self):
        t = lambda d, ch: {"date": d, "channel": ch, "direction": "outbound", "outcome": "sent"}
        touches = []
        for i in range(6):
            touches += [t("2026-09-%02d" % (10 + 2 * i), "voicemail"), t("2026-09-%02d" % (10 + 2 * i), "text")]
        touches.append({"date": "2026-09-30", "channel": "text", "direction": "inbound", "outcome": "replied"})
        self.assertEqual(C.fmt_followup(touches), "6 days of follow-up (6 calls, 6 texts)")
        self.assertEqual(C.fmt_followup(touches[:1]), "1 day of follow-up (1 call)")
        self.assertEqual(C.fmt_followup(touches[:2] + [t("2026-09-11", "unknown")]), "2 days of follow-up (3 follow-ups)")
        self.assertEqual(C.fmt_followup([]), "no follow-up logged yet")


class Identity(unittest.TestCase):
    def setUp(self):
        self.idn = C.load_identity()

    def test_brand_facts_come_from_identity_json(self):
        with open(C.default_identity_path(), encoding="utf-8") as f:
            raw = json.load(f)["identity"]
        self.assertEqual(self.idn["name"], raw["name"])
        self.assertEqual(self.idn["dre"], raw["dre"])
        self.assertEqual(self.idn["brand_line"], raw["brand_line"])
        self.assertTrue(self.idn["realtor_line"].endswith("\u00ae"))
        self.assertTrue(self.idn["disclaimer"])
        for k in ("phone", "email", "website", "brokerage", "team"):
            self.assertTrue(self.idn[k], k)

    def test_blocklist_is_exposed_and_enforced(self):
        bl = self.idn["blocklist"]
        self.assertTrue(bl["dre"] and bl["brand"])
        self.assertEqual(C.find_blocked("DRE " + bl["dre"][0], self.idn), [bl["dre"][0]])
        self.assertEqual(C.find_blocked("formerly with " + bl["brand"][0].upper(), self.idn), [bl["brand"][0]])
        self.assertEqual(C.find_blocked("DRE " + self.idn["dre"] + ", " + self.idn["brand_line"], self.idn), [])

    def test_another_agents_brokerage_is_kept_in_the_ledger_and_cut_on_the_page(self):
        brand = self.idn["blocklist"]["brand"][0]
        shown = C.display_brokerage(brand + " Services", self.idn)
        self.assertEqual(C.find_blocked(shown, self.idn), [])
        self.assertTrue(shown.startswith(brand.split()[0]))
        self.assertEqual(C.display_brokerage("Northgate Real Estate", self.idn), "Northgate")
        self.assertIsNone(C.display_brokerage(None, self.idn))
        d = load("ledger_small.json")
        contact(d, "c002")["brokerage"] = brand
        self.assertEqual(C.validate_ledger(d, identity=self.idn), [])
        contact(d, "c002")["feedback_safe"] = "He is with " + brand + "."
        self.assertTrue(any("blocked brand value" in p for p in C.validate_ledger(d, identity=self.idn)))

    def test_no_blocked_value_or_dash_in_this_skill(self):
        blocked = self.idn["blocklist"]["dre"] + self.idn["blocklist"]["brand"]
        for sub in ("scripts", "tests", "references"):
            for root, _, files in os.walk(os.path.join(SKILL, sub)):
                for name in files:
                    if not name.endswith((".py", ".md", ".json")):
                        continue
                    with open(os.path.join(root, name), encoding="utf-8") as f:
                        text = f.read()
                    for b in blocked:
                        self.assertNotIn(b.lower(), text.lower(), "%s holds a blocked value" % name)
                    self.assertFalse(C.has_dash(text), "%s holds an em dash or en dash" % name)


